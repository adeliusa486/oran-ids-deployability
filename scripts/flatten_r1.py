#!/usr/bin/env python3
"""Flatten the revision-1 manuscript into one main.tex for IEEE Access.

IEEE Access asks for the LaTeX source that produces the submitted PDF. As at
the first submission (scripts/make_submission.py), the source is ONE main.tex
with every \\input inlined (preamble, number macros, figure style, tables,
sections, TikZ figures) and the bibliography inlined, in one flat folder with
only the files it needs. This script also

  * orders the bibliography by first citation, as IEEE style requires, and
    drops entries that are not cited (the restructured text cites in a new
    order); it writes the sorted bibliography back to paper/r1/ so that the
    modular build and the flat build are the same document;
  * rewrites figure paths (figs/x.pdf -> x.pdf) and copies the figures,
    pictograms, author photographs, class and font files;
  * compiles the flat source three times with pdflatex and checks that the
    page count and the extracted text equal those of the modular build.

Usage:  python scripts/flatten_r1.py OUTDIR
"""
from __future__ import annotations

import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "paper" / "r1"


def inline(path: Path, seen=None) -> str:
    seen = seen or set()
    text = path.read_text(encoding="utf-8")

    def rep(m):
        name = m.group(1)
        f = SRC / (name if name.endswith(".tex") else name + ".tex")
        if not f.exists():
            raise FileNotFoundError(f"\\input{{{name}}}: {f}")
        if f in seen:
            raise RecursionError(f)
        return f"%\n% ---- inlined from {f.relative_to(SRC).as_posix()} ----\n" + \
            inline(f, seen | {f}).rstrip("\n") + "\n% ---- end of inlined file ----\n"

    out = []
    for line in text.splitlines(keepends=True):
        # the code part of a line ends at the first unescaped %
        m = re.search(r"(?<!\\)%", line)
        code, comment = (line[:m.start()], line[m.start():]) if m else (line, "")
        code = re.sub(r"\\input\{([^}]+)\}", rep, code)
        out.append(code + comment)
    return "".join(out)


def split_bib(text: str):
    start = text.index(r"\begin{thebibliography}")
    end = text.index(r"\end{thebibliography}") + len(r"\end{thebibliography}")
    return text[:start], text[start:end], text[end:]


def order_bibliography(body: str, bib: str):
    head_end = bib.index(r"\bibitem")
    head, items_txt = bib[:head_end], bib[head_end:bib.index(r"\end{thebibliography}")]
    items = {}
    order0 = []
    for blk in re.split(r"(?=\\bibitem\{)", items_txt):
        m = re.match(r"\\bibitem\{([^}]+)\}", blk)
        if m:
            items[m.group(1)] = blk.rstrip() + "\n\n"
            order0.append(m.group(1))
    cited = []
    for m in re.finditer(r"\\cite\{([^}]+)\}", body):
        for k in (x.strip() for x in m.group(1).split(",")):
            if k not in cited:
                cited.append(k)
    missing = [k for k in cited if k not in items]
    if missing:
        raise KeyError(f"cited but not in the bibliography: {missing}")
    dropped = [k for k in order0 if k not in cited]
    head = re.sub(r"\\begin\{thebibliography\}\{\d+\}", r"\\begin{thebibliography}{99}", head)
    return head + "".join(items[k] for k in cited) + r"\end{thebibliography}", cited, dropped


def main() -> int:
    out = Path(sys.argv[1]).resolve()
    out.mkdir(parents=True, exist_ok=True)
    # 1. sorted bibliography, shared by the modular and the flat build
    full = inline(SRC / "main.tex")
    pre, bib, post = split_bib(full)
    sorted_bib, cited, dropped = order_bibliography(pre + post, bib)
    (SRC / "bibliography_r1_sorted.tex").write_text(sorted_bib + "\n", encoding="utf-8")
    print(f"bibliography: {len(cited)} cited entries in citation order; dropped {dropped}")
    # 2. the flat source; the bibliography comes from references.bib via BibTeX
    flat = pre + "\\bibliographystyle{IEEEtran_doi}\n\\bibliography{references}" + post
    flat = flat.replace("{figs/", "{")
    header = ("%=======================================================================\n"
              "%  Flat submission source (revision 1): every input, table and number\n"
              "%  macro is inlined; references come from references.bib (style\n"
              "%  IEEEtran_doi.bst, main.bbl included). Generated by scripts/flatten_r1.py\n"
              "%  from paper/r1/ of the reproducibility repository.\n"
              "%  Build: pdflatex main; bibtex main; pdflatex main; pdflatex main\n"
              "%=======================================================================\n")
    (out / "main.tex").write_text(header + flat, encoding="utf-8")
    shutil.copy(SRC / "references_r1.bib", out / "references.bib")
    shutil.copy(ROOT / "paper" / "IEEEtran_doi.bst", out / "IEEEtran_doi.bst")
    # 3. the files it needs
    for f in SRC.glob("figs/*.pdf"):
        shutil.copy(f, out / f.name)
    pats = ["*.png", "*.jpg", "ieeeaccess.cls", "spotcolor.sty", "t1*.fd", "t1-*.pfb",
            "t1-*.tfm", "t1-*.map"]
    for pat in pats:
        for f in SRC.glob(pat):
            if not f.name.startswith("_"):
                shutil.copy(f, out / f.name)
    # 4. compile (pdflatex, bibtex, pdflatex x2) and compare with the modular build
    def tex(cmd):
        return subprocess.run(cmd, cwd=out, capture_output=True, text=True,
                              encoding="utf-8", errors="replace")
    tex(["pdflatex", "-interaction=nonstopmode", "main.tex"])
    b = tex(["bibtex", "main"])
    if b.returncode or "error" in (out / "main.blg").read_text(encoding="utf-8", errors="replace").lower():
        print("BibTeX failed:", b.stdout[-1500:])
        return 1
    for _ in range(2):
        tex(["pdflatex", "-interaction=nonstopmode", "main.tex"])
    log = (out / "main.log").read_text(encoding="utf-8", errors="replace")
    errors = [l for l in log.splitlines() if l.startswith("!") or "undefined" in l.lower()
              and ("citation" in l.lower() or "reference" in l.lower())]
    if errors:
        print("LaTeX errors:", errors[:5])
        return 1
    # the BibTeX entries must equal the verified list, entry by entry and in order
    def entries(t):
        t = t[t.index("\\bibitem"):t.index("\\end{thebibliography}")]
        t = t.replace("\\BIBentryALTinterwordspacing", "").replace("\\BIBentrySTDinterwordspacing", "")
        return [re.sub(r"\s+", " ", x).strip() for x in re.split(r"(?=\\bibitem\{)", t) if x.strip()]
    bbl = entries((out / "main.bbl").read_text(encoding="utf-8"))
    ref = entries(sorted_bib)
    if bbl != ref:
        diff = [(i + 1, x[:90], y[:90]) for i, (x, y) in enumerate(zip(bbl, ref)) if x != y]
        print(f"references.bib does not reproduce the verified list ({len(bbl)} vs {len(ref)}):", diff[:5])
        return 3
    print(f"references.bib reproduces all {len(bbl)} verified entries in order")
    for f in ("main.blg",):
        (out / f).unlink(missing_ok=True)
    import fitz
    a, b = fitz.open(SRC / "main.pdf"), fitz.open(out / "main.pdf")
    ta = "".join(p.get_text() for p in a)
    tb = "".join(p.get_text() for p in b)
    print(f"pages modular {len(a)}, flat {len(b)}; text identical: {ta == tb}")
    return 0 if len(a) == len(b) and ta == tb else 2


if __name__ == "__main__":
    sys.exit(main())
